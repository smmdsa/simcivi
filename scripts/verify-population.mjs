import assert from 'node:assert/strict';
import {Ecosystem} from '../dist/simulation.js';
import {HALF,POLE,distance} from '../dist/planet.js';
import {Neighborhood} from '../dist/lifeways.js';
const sim=new Ecosystem();
const female=sim.creatures.find(c=>c.species===0&&c.sex==='F');
const male=sim.creatures.find(c=>c.species===0&&c.sex==='M');
for(let i=sim.creatures.length;i<400;i++)sim.create(5,sim.point(5));
assert.equal(sim.creatures.length,400,'Creation must not depend on a global population quota');
for(const c of [female,male])Object.assign(c,{x:female.x,z:female.z,age:5,energy:100,cooldown:0});
assert(sim.court(male,female),'Marine population must not prevent terrestrial courtship');
const energy=female.energy+male.energy;
for(let i=0;i<160;i++)sim.progressPair(male,.1);
assert(female.pregnancy);
sim.giveBirth(female);
const child=sim.creatures.at(-1);
assert.equal(child.mother,female.id);
assert(female.energy+male.energy+child.energy<=energy,'Offspring reserves must come from parents');
assert.equal(sim.creatures.length,401);
Object.assign(male,{energy:20,cooldown:0});
assert(!sim.ready(male),'Hunger prevents reproduction');
const restored=new Ecosystem(JSON.parse(JSON.stringify(sim.snapshot())));
assert.equal(restored.creatures.length,401);
assert.deepEqual(restored.snapshot(),sim.snapshot());
const prey=sim.creatures.find(c=>c.species===2),hunter=sim.creatures.find(c=>c.species===3);
sim.kill(prey,'test');const corpse=sim.remains.at(-1),mass=corpse.biomass;
hunter.energy=0;
sim.eatRemains(hunter,corpse);
assert(corpse.biomass<mass,'Eating removes corpse biomass');
assert(hunter.energy>0);
corpse.biomass=0;const before=hunter.energy;sim.eatRemains(hunter,corpse);
assert.equal(hunter.energy,before,'Empty remains cannot feed twice');
console.log('PASS: uncapped reproduction, parental energy, hunger, persistence and finite carrion');
const active=new Ecosystem();
const pregnant=active.creatures.find(c=>c.sex==='F');
pregnant.pregnancy={remaining:20,total:40,reserve:40};
pregnant.energy=90;pregnant.recovery.mode='active';
pregnant.mind.job={action:'rest',x:pregnant.x,z:pregnant.z,until:20};
active.step(.1);
assert(pregnant.pregnancy.remaining<20,'Cultural work must not pause gestation');
const sheltered=new Ecosystem(),resting=sheltered.creatures[0];
for(let level=0;level<4;level++)sheltered.culture.blocks.push({id:10000+level,x:resting.x+1,z:resting.z,level,type:0,health:1,owner:resting.id});
sheltered.culture.index();assert(sheltered.culture.shelter(resting.x,resting.z)>0);resting.energy=70;
resting.mind.job={action:'rest',x:resting.x,z:resting.z,until:20};
sheltered.culture.updateAgent(resting,.1);
assert(resting.energy<=70,'Shelter cannot create food energy');
console.log('PASS: pregnancy continues during activity and shelter cannot generate reserves');
const old=sim.snapshot();
const oldMother=old.creatures.find(c=>c.id===female.id);
oldMother.energy=90;oldMother.pregnancy={remaining:10,total:40,father:male.id,fatherDna:male.dna,fatherGeneration:1};
const migrated=new Ecosystem(old),mother=migrated.byId.get(female.id);
assert.equal(mother.energy+mother.pregnancy.reserve,90);
const again=new Ecosystem(migrated.snapshot());
assert.deepEqual(again.snapshot(),migrated.snapshot(),'Legacy pregnancy is charged only once');
for(let i=0;i<10;i++){migrated.step(.1);again.step(.1);}
assert.deepEqual(again.snapshot(),migrated.snapshot(),'Continuation remains deterministic');
console.log('PASS: legacy pregnancy reserve migrates once with deterministic continuation');
const hunting=new Ecosystem(),predator=hunting.creatures.find(c=>c.species===3),victim=hunting.creatures.find(c=>c.species===0);
Object.assign(victim,{x:predator.x,z:predator.z,health:1});
Object.assign(predator,{energy:40,target:{x:victim.x,z:victim.z,id:victim.id,kind:'prey'},think:10});
predator.mind.job=null;predator.social.intent=null;
hunting.step(.1);
assert(!hunting.byId.has(victim.id),'Actual attack kills the weakened prey');
const meat=hunting.remains.find(r=>r.id===victim.id);
assert(meat.biomass<meat.originalBiomass,'The killing bite consumes the same corpse');
const meatBefore=meat.biomass,energyBefore=predator.energy;
hunting.eatRemains(predator,meat);
assert(Math.abs(predator.energy-energyBefore-(meatBefore-meat.biomass)*6)<1e-8);
assert.deepEqual(new Ecosystem(hunting.snapshot()).snapshot(),hunting.snapshot());
console.log('PASS: predation and scavenging share one finite carcass');

const seam=[{x:HALF-.1,z:0},{x:-HALF+.1,z:0}],polar=[{x:0,z:POLE-.05},{x:HALF-.1,z:POLE-.05}];
for(const pair of [seam,polar])assert.equal(new Neighborhood(pair,10).near(pair[0],.5).length,2);
for(let i=0;i<30;i++){const destination=sim.explore(female);if(destination)assert(distance(female,destination)<=6.000001);}
console.log('PASS: spherical neighbors and local exploration');
